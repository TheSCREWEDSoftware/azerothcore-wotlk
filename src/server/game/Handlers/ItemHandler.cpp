void WorldSession::HandleSplitItemOpcode(WorldPackets::Item::SplitItem& packet)
{
    //LOG_DEBUG("network.opcode", "WORLD: CMSG_SPLIT_ITEM");

    uint16 src = ((packet.FromPackSlot << 8) | packet.FromSlot);
    uint16 dst = ((packet.ToPackSlot << 8) | packet.ToSlot);

    if (src == dst)
        return;

    if (packet.Quantity == 0)
        return; //check count - if zero it's fake packet

    if (!_player->IsValidPos(packet.FromPackSlot, packet.FromSlot, true))
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, nullptr, nullptr);
        return;
    }

    if (!_player->IsValidPos(packet.ToPackSlot, packet.ToSlot, false)) // can be autostore pos
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, nullptr, nullptr);
        return;
    }

    _player->SplitItem(src, dst, packet.Quantity);
}

void WorldSession::HandleSwapInvItemOpcode(WorldPackets::Item::SwapInvItem& packet)
{
    //LOG_DEBUG("network.opcode", "WORLD: CMSG_SWAP_INV_ITEM");

    // prevent attempt swap same item to current position generated by client at special cheating sequence
    if (packet.Slot1 == packet.Slot2)
        return;

    if (!_player->IsValidPos(INVENTORY_SLOT_BAG_0, packet.Slot1, true))
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, nullptr, nullptr);
        return;
    }

    if (!_player->IsValidPos(INVENTORY_SLOT_BAG_0, packet.Slot2, true))
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, nullptr, nullptr);
        return;
    }

    if (_player->IsBankPos(INVENTORY_SLOT_BAG_0, packet.Slot1) && !CanUseBank())
    {
        //LOG_DEBUG("network", "WORLD: HandleSwapInvItemOpcode - Unit ({}) not found or you can't interact with him.", m_currentBankerGUID.ToString());
        return;
    }

    if (_player->IsBankPos(INVENTORY_SLOT_BAG_0, packet.Slot2) && !CanUseBank())
    {
        //LOG_DEBUG("network", "WORLD: HandleSwapInvItemOpcode - Unit ({}) not found or you can't interact with him.", m_currentBankerGUID.ToString());
        return;
    }

    uint16 src = ((INVENTORY_SLOT_BAG_0 << 8) | packet.Slot1);
    uint16 dst = ((INVENTORY_SLOT_BAG_0 << 8) | packet.Slot2);

    _player->SwapItem(src, dst);
}

void WorldSession::HandleAutoEquipItemSlotOpcode(WorldPackets::Item::AutoEquipItemSlot& packet)
{
    // cheating attempt, client should never send opcode in that case
    if (!Player::IsEquipmentPos(INVENTORY_SLOT_BAG_0, packet.ItemDstSlot))
        return;

    Item* item = _player->GetItemByGuid(packet.Item);
    uint16 dstpos = packet.ItemDstSlot | (INVENTORY_SLOT_BAG_0 << 8);

    if (!item || item->GetPos() == dstpos)
        return;

    _player->SwapItem(item->GetPos(), dstpos);
}

void WorldSession::HandleSwapItem(WorldPackets::Item::SwapItem& packet)
{
    //LOG_DEBUG("network.opcode", "WORLD: CMSG_SWAP_ITEM");

    uint16 src = ((packet.ContainerSlotA << 8) | packet.SlotA);
    uint16 dst = ((packet.ContainerSlotB << 8) | packet.SlotB);

    // prevent attempt swap same item to current position generated by client at special cheating sequence
    if (src == dst)
        return;

    if (!_player->IsValidPos(packet.ContainerSlotA, packet.SlotA, true))
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, nullptr, nullptr);
        return;
    }

    if (!_player->IsValidPos(packet.ContainerSlotB, packet.SlotB, true))
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, nullptr, nullptr);
        return;
    }

    if (_player->IsBankPos(packet.ContainerSlotA, packet.SlotA) && !CanUseBank())
    {
        //LOG_DEBUG("network", "WORLD: HandleSwapItem - Unit ({}) not found or you can't interact with him.", m_currentBankerGUID.ToString());
        return;
    }

    if (_player->IsBankPos(packet.ContainerSlotB, packet.SlotB) && !CanUseBank())
    {
        //LOG_DEBUG("network", "WORLD: HandleSwapItem - Unit ({}) not found or you can't interact with him.", m_currentBankerGUID.ToString());
        return;
    }

    _player->SwapItem(src, dst);
}

void WorldSession::HandleAutoEquipItemOpcode(WorldPackets::Item::AutoEquipItem& packet)
{
    //LOG_DEBUG("network.opcode", "WORLD: CMSG_AUTOEQUIP_ITEM");

    Item* pSrcItem  = _player->GetItemByPos(packet.PackSlot, packet.Slot);
    if (!pSrcItem)
        return;                                             // only at cheat

    ItemTemplate const* pProto = pSrcItem->GetTemplate();
    if (!pProto)
    {
        _player->SendEquipError(pSrcItem->IsBag() ? EQUIP_ERR_ITEM_NOT_FOUND : EQUIP_ERR_ITEMS_CANT_BE_SWAPPED, pSrcItem);
        return;
    }

    uint8 eslot = _player->FindEquipSlot(pProto, NULL_SLOT, !pSrcItem->IsBag());
    if (eslot == NULL_SLOT)
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_CANT_BE_EQUIPPED, pSrcItem);
        return;
    }

    uint16 src = pSrcItem->GetPos();
    uint16 dest = ((INVENTORY_SLOT_BAG_0 << 8) | eslot);
    if (dest == src) // prevent equip in same slot, only at cheat
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_CANT_BE_EQUIPPED, pSrcItem);
        return;
    }

    Item* pDstItem = _player->GetItemByPos(dest);

    // Remove item enchantments for now and restore it later
    // Needed for swap sanity checks
    if (pDstItem)
    {
        _player->ApplyEnchantment(pDstItem, false);
    }

    InventoryResult msg = _player->CanEquipItem(NULL_SLOT, dest, pSrcItem, !pSrcItem->IsBag());
    if (msg != EQUIP_ERR_OK)
    {
        // Restore enchantments
        if (pDstItem)
        {
            _player->ApplyEnchantment(pDstItem, true);
        }

        _player->SendEquipError(msg, pSrcItem, nullptr);
        return;
    }

    if (!pDstItem)                                         // empty slot, simple case
    {
        _player->RemoveItem(packet.PackSlot, packet.Slot, true);
        _player->EquipItem(dest, pSrcItem, true);
        _player->AutoUnequipOffhandIfNeed();
    }
    else                                                    // have currently equipped item, not simple case
    {
        // Restore enchantments
        _player->ApplyEnchantment(pDstItem, true);

        uint8 dstbag = pDstItem->GetBagSlot();
        uint8 dstslot = pDstItem->GetSlot();

        msg = _player->CanUnequipItem(dest, !pSrcItem->IsBag());
        if (msg != EQUIP_ERR_OK)
        {
            _player->SendEquipError(msg, pDstItem, nullptr);
            return;
        }

        // check dest->src move possibility
        ItemPosCountVec sSrc;
        uint16 eSrc = 0;
        if (_player->IsInventoryPos(src))
        {
            msg = _player->CanStoreItem(packet.PackSlot, packet.Slot, sSrc, pDstItem, true);
            if (msg != EQUIP_ERR_OK)
                msg = _player->CanStoreItem(packet.PackSlot, NULL_SLOT, sSrc, pDstItem, true);
            if (msg != EQUIP_ERR_OK)
                msg = _player->CanStoreItem(NULL_BAG, NULL_SLOT, sSrc, pDstItem, true);
        }
        else if (_player->IsBankPos(src))
        {
            msg = _player->CanBankItem(packet.PackSlot, packet.Slot, sSrc, pDstItem, true);
            if (msg != EQUIP_ERR_OK)
                msg = _player->CanBankItem(packet.PackSlot, NULL_SLOT, sSrc, pDstItem, true);
            if (msg != EQUIP_ERR_OK)
                msg = _player->CanBankItem(NULL_BAG, NULL_SLOT, sSrc, pDstItem, true);
        }
        else if (_player->IsEquipmentPos(src))
        {
            msg = _player->CanEquipItem(packet.Slot, eSrc, pDstItem, true);
            if (msg == EQUIP_ERR_OK)
                msg = _player->CanUnequipItem(eSrc, true);
        }

        if (msg != EQUIP_ERR_OK)
        {
            _player->SendEquipError(msg, pDstItem, pSrcItem);
            return;
        }

        // now do moves, remove...
        _player->RemoveItem(dstbag, dstslot, true);
        _player->RemoveItem(packet.PackSlot, packet.Slot, true);

        // add to dest
        _player->EquipItem(dest, pSrcItem, true);

        // add to src
        if (_player->IsInventoryPos(src))
            _player->StoreItem(sSrc, pDstItem, true);
        else if (_player->IsBankPos(src))
            _player->BankItem(sSrc, pDstItem, true);
        else if (_player->IsEquipmentPos(src))
            _player->EquipItem(eSrc, pDstItem, true);

        _player->AutoUnequipOffhandIfNeed();

        // Xinef: Call this here after all needed items are equipped
        _player->RemoveItemDependentAurasAndCasts((Item*)nullptr);
    }
}

void WorldSession::HandleDestroyItemOpcode(WorldPackets::Item::DestroyItem& packet)
{
    //LOG_DEBUG("network.opcode", "WORLD: CMSG_DESTROYITEM");

    uint16 pos = (packet.ContainerId << 8) | packet.SlotNum;

    // prevent drop unequipable items (in combat, for example) and non-empty bags
    if (_player->IsEquipmentPos(pos) || _player->IsBagPos(pos))
    {
        InventoryResult msg = _player->CanUnequipItem(pos, false);
        if (msg != EQUIP_ERR_OK)
        {
            _player->SendEquipError(msg, _player->GetItemByPos(pos), nullptr);
            return;
        }
    }

    Item* pItem  = _player->GetItemByPos(packet.ContainerId, packet.SlotNum);
    if (!pItem)
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, nullptr, nullptr);
        return;
    }

    if (pItem->GetTemplate()->HasFlag(ITEM_FLAG_NO_USER_DESTROY))
    {
        _player->SendEquipError(EQUIP_ERR_CANT_DROP_SOULBOUND, nullptr, nullptr);
        return;
    }

    ItemRecovery::Save(pItem, packet.Count ? std::min<uint32>(packet.Count, pItem->GetCount()) : pItem->GetCount(), RECOVERY_ITEM_SOURCE_DESTROYED);

    if (packet.Count)
    {
        uint32 i_count = packet.Count;
        _player->DestroyItemCount(pItem, i_count, true);
    }
    else
    {
        _player->DestroyItem(packet.ContainerId, packet.SlotNum, true);
    }
    _player->SendQuestGiverStatusMultiple();
}

bool ItemTemplate::HasStat(ItemModType stat) const
{
    for (uint8 i = 0; i < MAX_ITEM_PROTO_STATS; ++i)
    {
        if (i >= StatsCount)
        {
            break;
        }

        if (ItemStat[i].ItemStatType == stat)
        {
            return true;
        }
    }

    return false;
}

bool ItemTemplate::HasSpellPowerStat() const
{
    bool invalid = false;
    for (uint8 i = 0; i < MAX_ITEM_PROTO_SPELLS; ++i)
    {
        _Spell const& spellData = Spells[i];
        if (!spellData.SpellId)
        {
            continue;
        }

        SpellInfo const* spellInfo = sSpellMgr->GetSpellInfo(spellData.SpellId);
        if (!spellInfo)
        {
            continue;
        }

        for (uint8 j = EFFECT_0; j <= EFFECT_2; ++j)
        {
            switch (spellInfo->Effects[j].ApplyAuraName)
            {
                case SPELL_AURA_MOD_HEALING_DONE:
                case SPELL_AURA_MOD_SPELL_HEALING_OF_STAT_PERCENT:
                case SPELL_AURA_MOD_SPELL_HEALING_OF_ATTACK_POWER:
                case SPELL_AURA_MOD_HEALING:
                    invalid = true;
                    break;
                case SPELL_AURA_MOD_DAMAGE_DONE:
                case SPELL_AURA_MOD_SPELL_DAMAGE_OF_STAT_PERCENT:
                case SPELL_AURA_MOD_SPELL_DAMAGE_OF_ATTACK_POWER:
                case SPELL_AURA_MOD_DAMAGE_TAKEN:
                    if (!(spellInfo->Effects[j].MiscValue & SPELL_SCHOOL_MASK_SPELL))
                    {
                        return false;
                    }
                    invalid = true;
                    break;
                default:
                    break;
            }
        }
    }

    return invalid;
}

// Only _static_ data send in this packet !!!
void WorldSession::HandleReadItem(WorldPackets::Item::ReadItem& packet)
{
    Item* pItem = _player->GetItemByPos(packet.PackSlot, packet.Slot);

    if (pItem && pItem->GetTemplate()->PageText)
    {
        InventoryResult msg = _player->CanUseItem(pItem);
        if (msg == EQUIP_ERR_OK)
        {
            WorldPackets::Item::ReadItemResultOK readItemResultOK;
            readItemResultOK.Item = pItem->GetGUID();
            SendPacket(readItemResultOK.Write());
            LOG_DEBUG("network.opcode", "STORAGE: Item page sent");
        }
        else
        {
            // the 6.x failure subcodes are unknown; the equip error tells the client why
            LOG_DEBUG("network.opcode", "STORAGE: Unable to read item");
            _player->SendEquipError(msg, pItem, nullptr);
        }
    }
    else
        _player->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, nullptr, nullptr);
}

void WorldSession::HandleSellItemOpcode(WorldPackets::Item::SellItem& packet)
{
    if (!packet.ItemGUID)
        return;

    Creature* creature = GetPlayer()->GetNPCIfCanInteractWith(packet.VendorGUID, UNIT_NPC_FLAG_VENDOR);
    if (!creature)
    {
        LOG_DEBUG("network", "WORLD: HandleSellItemOpcode - Unit ({}) not found or you can not interact with him.", packet.VendorGUID.ToString());
        _player->SendSellError(SELL_ERR_CANT_FIND_VENDOR, nullptr, packet.ItemGUID, 0);
        return;
    }

    if (creature->HasFlagsExtra(CREATURE_FLAG_EXTRA_NO_SELL_VENDOR))
    {
        _player->SendSellError(SELL_ERR_CANT_SELL_TO_THIS_MERCHANT, creature, packet.ItemGUID, 0);
        return;
    }

    // remove fake death
    if (GetPlayer()->HasUnitState(UNIT_STATE_DIED))
        GetPlayer()->RemoveAurasByType(SPELL_AURA_FEIGN_DEATH);

    Item* pItem = _player->GetItemByGuid(packet.ItemGUID);
    if (pItem)
    {
        if (!sScriptMgr->OnPlayerCanSellItem(_player, pItem, creature))
        {
            _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
            return;
        }

        // prevent sell not owner item
        if (_player->GetGUID() != pItem->GetOwnerGUID())
        {
            _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
            return;
        }

        // prevent sell non empty bag by drag-and-drop at vendor's item list
        if (pItem->IsNotEmptyBag())
        {
            _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
            return;
        }

        // prevent sell currently looted item
        if (_player->GetLootGUID() == pItem->GetGUID())
        {
            _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
            return;
        }

        // prevent selling item for sellprice when the item is still refundable
        // this probably happens when right clicking a refundable item, the client sends both
        // CMSG_SELL_ITEM and CMSG_REFUND_ITEM (unverified)
        if (pItem->IsRefundable())
            return; // Therefore, no feedback to client

        // special case at auto sell (sell all)
        if (packet.Amount == 0)
            packet.Amount = pItem->GetCount();
        else
        {
            // prevent sell more items that exist in stack (possible only not from client)
            if (packet.Amount > pItem->GetCount())
            {
                _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
                return;
            }
        }

        ItemTemplate const* pProto = pItem->GetTemplate();
        if (pProto)
        {
            if (pProto->SellPrice > 0)
            {
                uint32 money = pProto->SellPrice * packet.Amount;
                if (_player->GetMoney() >= MAX_MONEY_AMOUNT - money)               // prevent exceeding gold limit
                {
                    _player->SendEquipError(EQUIP_ERR_TOO_MUCH_GOLD, nullptr, nullptr);
                    _player->SendSellError(SELL_ERR_UNK, creature, packet.ItemGUID, 0);
                    return;
                }

                uint32 maxDurability = pItem->GetUInt32Value(ITEM_FIELD_MAXDURABILITY);
                if (maxDurability)
                {
                    uint32 curDurability = pItem->GetUInt32Value(ITEM_FIELD_DURABILITY);
                    uint32 LostDurability = maxDurability - curDurability;

                    if (LostDurability > 0)
                    {
                        DurabilityCostsEntry const* dcost = sDurabilityCostsStore.LookupEntry(pProto->ItemLevel);
                        if (!dcost)
                        {
                            _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
                            LOG_ERROR("network.opcode", "WORLD: HandleSellItemOpcode - Wrong item lvl {} for item {} count = {}", pProto->ItemLevel, pItem->GetEntry(), packet.Amount);
                            return;
                        }

                        uint32 dQualitymodEntryId = (pProto->Quality + 1) * 2;
                        DurabilityQualityEntry const* dQualitymodEntry = sDurabilityQualityStore.LookupEntry(dQualitymodEntryId);
                        if (!dQualitymodEntry)
                        {
                            _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
                            LOG_ERROR("network.opcode", "WORLD: HandleSellItemOpcode - Wrong dQualityModEntry {} for item {} count = {}", dQualitymodEntryId, pItem->GetEntry(), packet.Amount);
                            return;
                        }

                        uint32 dmultiplier = GetDurabilityCostMultiplier(dcost, pProto->Class, pProto->SubClass);
                        uint32 refund = uint32(std::ceil(LostDurability * dmultiplier * double(dQualitymodEntry->QualityMod) * pItem->GetRepairCostMultiplier()));

                        if (!refund)
                            refund = 1;

                        //starter items can cost more to refund than vendorprice
                        if (refund > money)
                            money = 1;
                        else
                            money -= refund;
                    }
                }

                Item* soldItem = pItem;
                if (packet.Amount < pItem->GetCount())               // need split items
                {
                    Item* pNewItem = pItem->CloneItem(packet.Amount, _player);
                    if (!pNewItem)
                    {
                        LOG_ERROR("network.opcode", "WORLD: HandleSellItemOpcode - could not create clone of item {}; count = {}", pItem->GetEntry(), packet.Amount);
                        _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
                        return;
                    }

                    pNewItem->SetUInt32Value(ITEM_FIELD_DURABILITY, pItem->GetUInt32Value(ITEM_FIELD_DURABILITY));

                    pItem->SetCount(pItem->GetCount() - packet.Amount);
                    _player->ItemRemovedQuestCheck(pItem->GetEntry(), packet.Amount);
                    if (_player->IsInWorld())
                        pItem->SendUpdateToPlayer(_player);
                    pItem->SetState(ITEM_CHANGED, _player);

                    _player->AddItemToBuyBackSlot(pNewItem, money);
                    if (_player->IsInWorld())
                        pNewItem->SendUpdateToPlayer(_player);

                    soldItem = pNewItem;
                }
                else
                {
                    _player->ItemRemovedQuestCheck(pItem->GetEntry(), pItem->GetCount());
                    _player->RemoveItem(pItem->GetBagSlot(), pItem->GetSlot(), true);
                    pItem->RemoveFromUpdateQueueOf(_player);
                    _player->AddItemToBuyBackSlot(pItem, money);
                    _player->UpdateTitansGrip();
                }

                // A trial account at its money cap is refused the credit, and then nothing is owed back
                bool const paid = _player->ModifyMoney(money);
                if (sWorld->getBoolConfig(CONFIG_ITEMDELETE_VENDOR))
                    ItemRecovery::Save(soldItem, packet.Amount, RECOVERY_ITEM_SOURCE_VENDORED, paid ? money : 0);

                _player->UpdateAchievementCriteria(ACHIEVEMENT_CRITERIA_TYPE_MONEY_FROM_VENDORS, money);
            }
            else
                _player->SendSellError(SELL_ERR_CANT_SELL_ITEM, creature, packet.ItemGUID, 0);
            return;
        }
    }
    _player->SendSellError(SELL_ERR_CANT_FIND_ITEM, creature, packet.ItemGUID, 0);
    return;
}

void WorldSession::HandleBuybackItem(WorldPackets::Item::BuyBackItem& packet)
{
    Creature* creature = GetPlayer()->GetNPCIfCanInteractWith(packet.VendorGUID, UNIT_NPC_FLAG_VENDOR);
    if (!creature)
    {
        LOG_DEBUG("network", "WORLD: HandleBuybackItem - Unit ({}) not found or you can not interact with him.", packet.VendorGUID.ToString());
        _player->SendSellError(SELL_ERR_CANT_FIND_VENDOR, nullptr, ObjectGuid::Empty, 0);
        return;
    }

    // remove fake death
    if (GetPlayer()->HasUnitState(UNIT_STATE_DIED))
        GetPlayer()->RemoveAurasByType(SPELL_AURA_FEIGN_DEATH);

    Item* pItem = _player->GetItemFromBuyBackSlot(packet.Slot);
    if (pItem)
    {
        uint32 price = _player->GetUInt32Value(PLAYER_FIELD_BUYBACK_PRICE_1 + packet.Slot - BUYBACK_SLOT_START);
        if (!_player->HasEnoughMoney(price))
        {
            _player->SendBuyError(BUY_ERR_NOT_ENOUGHT_MONEY, creature, pItem->GetEntry(), 0);
            return;
        }

        ItemPosCountVec dest;
        InventoryResult msg = _player->CanStoreItem(NULL_BAG, NULL_SLOT, dest, pItem, false);
        if (msg == EQUIP_ERR_OK)
        {
            if (sWorld->getBoolConfig(CONFIG_ITEMDELETE_VENDOR))
            {
                CharacterDatabasePreparedStatement* stmt = CharacterDatabase.GetPreparedStatement(CHAR_DEL_RECOVERY_ITEM);
                stmt->SetData(0, _player->GetGUID().GetCounter());
                stmt->SetData(1, pItem->GetEntry());
                stmt->SetData(2, pItem->GetGUID().GetCounter());
                stmt->SetData(3, uint8(RECOVERY_ITEM_SOURCE_VENDORED));
                // Synchronous: the item leaves the buyback tab below, and a restore must not find the row after that
                CharacterDatabase.DirectExecute(stmt);
            }

            _player->ModifyMoney(-(int32)price);
            _player->RemoveItemFromBuyBackSlot(packet.Slot, false);
            _player->ItemAddedQuestCheck(pItem->GetEntry(), pItem->GetCount());
            _player->StoreItem(dest, pItem, true);
        }
        else
            _player->SendEquipError(msg, pItem, nullptr);
        return;
    }
    else
        _player->SendBuyError(BUY_ERR_CANT_FIND_ITEM, creature, 0, 0);
}

void WorldSession::HandleBuyItemOpcode(WorldPackets::Item::BuyItem& packet)
{
    // client expects count starting at 1, and we send vendorslot+1 to client already
    if (packet.Muid > 0)
        --packet.Muid;
    else
        return; // cheating

    if (packet.ItemType == ITEM_VENDOR_TYPE_CURRENCY)
    {
        // npc_vendor has no currency rows yet, so a currency purchase can't match a vendor slot
        LOG_DEBUG("network", "WORLD: HandleBuyItemOpcode - currency {} is not a supported vendor item", packet.Item.ItemID);
        return;
    }

    if (packet.ItemType != ITEM_VENDOR_TYPE_ITEM)
    {
        LOG_DEBUG("network", "WORLD: HandleBuyItemOpcode - wrong itemType {} in CMSG_BUY_ITEM", uint32(packet.ItemType));
        return;
    }

    if (packet.Quantity <= 0)
        return;

    uint8 bag = NULL_BAG;
    Item* bagItem = _player->GetItemByGuid(packet.ContainerGUID);
    if (bagItem && bagItem->IsBag())
        bag = bagItem->GetSlot();
    else if (packet.ContainerGUID == _player->GetGUID()) // The client sends the player guid when storing an item in the default backpack
        bag = INVENTORY_SLOT_BAG_0;

    GetPlayer()->BuyItemFromVendorSlot(packet.VendorGUID, packet.Muid, packet.Item.ItemID, uint32(packet.Quantity), bag, uint8(packet.Slot));
}

void WorldSession::HandleTransmogrifyItems(WorldPackets::Item::TransmogrifyItems& packet)
{
    Player* player = GetPlayer();

    if (packet.Items.size() >= EQUIPMENT_SLOT_END)
    {
        LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify more items than possible ({}).",
            player->GetGUID().ToString(), uint32(packet.Items.size()));
        return;
    }

    if (!player->GetNPCIfCanInteractWith(packet.Npc, UNIT_NPC_FLAG_TRANSMOGRIFIER))
    {
        LOG_DEBUG("network", "HandleTransmogrifyItems: {} not found or player can't interact with it.",
            packet.Npc.ToString());
        return;
    }

    // Validate every slot before changing anything
    int64 cost = 0;
    std::unordered_map<Item*, Item*> transmogItems;
    std::unordered_map<Item*, VoidStorageItem*> transmogVoidItems;
    std::vector<Item*> resetAppearanceItems;

    for (WorldPackets::Item::TransmogrifyItem const& transmogItem : packet.Items)
    {
        // slot of the transmogrified item
        if (transmogItem.Slot >= EQUIPMENT_SLOT_END)
        {
            LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify a wrong slot ({}).",
                player->GetGUID().ToString(), transmogItem.Slot);
            return;
        }

        // transmogrified item
        Item* itemTransmogrified = player->GetItemByPos(INVENTORY_SLOT_BAG_0, uint8(transmogItem.Slot));
        if (!itemTransmogrified)
        {
            LOG_DEBUG("network", "HandleTransmogrifyItems: {} has no item in transmogrify slot {}.",
                player->GetGUID().ToString(), transmogItem.Slot);
            return;
        }

        if (player->CanUseItem(itemTransmogrified->GetTemplate()) != EQUIP_ERR_OK)
        {
            LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify an unusable item in slot {}.",
                player->GetGUID().ToString(), transmogItem.Slot);
            return;
        }

        uint32 transmogrifierEntry = 0;
        if (transmogItem.SrcItemGUID)
        {
            // guid of the transmogrifier item
            Item* itemTransmogrifier = player->GetItemByGuid(*transmogItem.SrcItemGUID);
            if (!itemTransmogrifier)
            {
                LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify with an invalid item ({}).",
                    player->GetGUID().ToString(), transmogItem.SrcItemGUID->ToString());
                return;
            }

            if (player->CanUseItem(itemTransmogrifier->GetTemplate()) != EQUIP_ERR_OK)
            {
                LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify with an unusable item ({}).",
                    player->GetGUID().ToString(), transmogItem.SrcItemGUID->ToString());
                return;
            }

            // validity of the transmogrification items
            if (!Item::CanTransmogrifyItemWithItem(itemTransmogrified, itemTransmogrifier))
            {
                LOG_DEBUG("network", "HandleTransmogrifyItems: {} failed CanTransmogrifyItemWithItem ({} with {}).",
                    player->GetGUID().ToString(), itemTransmogrified->GetEntry(), itemTransmogrifier->GetEntry());
                return;
            }

            transmogrifierEntry = itemTransmogrifier->GetEntry();
            transmogItems[itemTransmogrified] = itemTransmogrifier;
        }
        else if (transmogItem.SrcVoidItemGUID)
        {
            // guid of the transmogrifier item in void storage
            uint8 slot;
            VoidStorageItem* itemTransmogrifier = player->GetVoidStorageItem(transmogItem.SrcVoidItemGUID->GetCounter(), slot);
            if (!itemTransmogrifier)
            {
                LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify with an invalid void storage item ({}).",
                    player->GetGUID().ToString(), transmogItem.SrcVoidItemGUID->ToString());
                return;
            }

            ItemTemplate const* transmogrifierTemplate = sObjectMgr->GetItemTemplate(itemTransmogrifier->ItemEntry);
            if (!transmogrifierTemplate || player->CanUseItem(transmogrifierTemplate) != EQUIP_ERR_OK)
            {
                LOG_DEBUG("network", "HandleTransmogrifyItems: {} tried to transmogrify with an unusable void storage item ({}).",
                    player->GetGUID().ToString(), transmogItem.SrcVoidItemGUID->ToString());
                return;
            }

            if (!Item::CanTransmogrifyItemWithTemplate(itemTransmogrified, transmogrifierTemplate))
            {
                LOG_DEBUG("network", "HandleTransmogrifyItems: {} failed CanTransmogrifyItemWithItem ({} with {}).",
                    player->GetGUID().ToString(), itemTransmogrified->GetEntry(), itemTransmogrifier->ItemEntry);
                return;
            }

            transmogrifierEntry = itemTransmogrifier->ItemEntry;
            transmogVoidItems[itemTransmogrified] = itemTransmogrifier;
        }
        else
        {
            resetAppearanceItems.push_back(itemTransmogrified);
            continue;
        }

        // entry of transmogrifier and from packet
        if (transmogrifierEntry != transmogItem.Item.ItemID)
        {
            LOG_DEBUG("network", "HandleTransmogrifyItems: {} sent item {} for transmogrifier {}.",
                player->GetGUID().ToString(), transmogItem.Item.ItemID, transmogrifierEntry);
            return;
        }

        cost += itemTransmogrified->GetSpecialPrice();
    }

    if (cost) // 0 cost if only reverting looks
    {
        if (!player->HasEnoughMoney(cost))
            return;

        player->ModifyMoney(-cost);
    }

    // Everything is fine, proceed
    for (auto const& [transmogrified, transmogrifier] : transmogItems)
    {
        transmogrified->SetModifier(ITEM_MODIFIER_TRANSMOG_ITEM_ID, transmogrifier->GetEntry());
        transmogrified->SetModifier(ITEM_MODIFIER_TRANSMOG_APPEARANCE_MOD, transmogrifier->GetAppearanceModId());
        player->SetVisibleItemSlot(transmogrified->GetSlot(), transmogrified);

        transmogrified->UpdatePlayedTime(player);
        transmogrified->SetOwnerGUID(player->GetGUID());
        transmogrified->SetNotRefundable(player);
        transmogrified->ClearSoulboundTradeable(player);

        if (transmogrifier->GetTemplate()->Bonding == BIND_WHEN_EQUIPPED || transmogrifier->GetTemplate()->Bonding == BIND_WHEN_USE)
            transmogrifier->SetBinding(true);

        transmogrifier->SetOwnerGUID(player->GetGUID());
        transmogrifier->SetNotRefundable(player);
        transmogrifier->ClearSoulboundTradeable(player);

        transmogrified->SetState(ITEM_CHANGED, player);
    }

    for (auto const& [transmogrified, transmogrifier] : transmogVoidItems)
    {
        transmogrified->SetModifier(ITEM_MODIFIER_TRANSMOG_ITEM_ID, transmogrifier->ItemEntry);
        transmogrified->SetModifier(ITEM_MODIFIER_TRANSMOG_APPEARANCE_MOD, 0);
        player->SetVisibleItemSlot(transmogrified->GetSlot(), transmogrified);

        transmogrified->SetNotRefundable(player);
        transmogrified->ClearSoulboundTradeable(player);
        transmogrified->SetState(ITEM_CHANGED, player);
    }

    for (Item* item : resetAppearanceItems)
    {
        item->SetModifier(ITEM_MODIFIER_TRANSMOG_ITEM_ID, 0);
        item->SetModifier(ITEM_MODIFIER_TRANSMOG_APPEARANCE_MOD, 0);
        item->SetState(ITEM_CHANGED, player);
        player->SetVisibleItemSlot(item->GetSlot(), item);
    }
}

