void WorldSession::HandleUpgradeItem(WorldPackets::Item::UpgradeItem& packet)
{
    WorldPackets::Item::ItemUpgradeResult itemUpgradeResult;
    if (!_player->GetNPCIfCanInteractWith(packet.ItemMaster, UNIT_NPC_FLAG_NONE, UNIT_NPC_FLAG_2_ITEM_UPGRADE_MASTER))
    {
        LOG_DEBUG("network", "WORLD: HandleUpgradeItem - {} not found or player can't interact with it.", packet.ItemMaster.ToString());
        itemUpgradeResult.Success = false;
        SendPacket(itemUpgradeResult.Write());
        return;
    }

    Item* item = _player->GetItemByGuid(packet.ItemGUID);
    if (!item)
    {
        LOG_DEBUG("network", "WORLD: HandleUpgradeItem - item {} not found!", packet.ItemGUID.ToString());
        itemUpgradeResult.Success = false;
        SendPacket(itemUpgradeResult.Write());
        return;
    }

    ItemUpgradeEntry const* itemUpgradeEntry = sItemUpgradeStore.LookupEntry(packet.UpgradeID);
    if (!itemUpgradeEntry)
    {
        LOG_DEBUG("network", "WORLD: HandleUpgradeItem - ItemUpgradeEntry ({}) not found.", packet.UpgradeID);
        itemUpgradeResult.Success = false;
        SendPacket(itemUpgradeResult.Write());
        return;
    }

    // Check if player has enough currency
    if (!_player->HasCurrency(itemUpgradeEntry->CurrencyID, itemUpgradeEntry->CurrencyCost))
    {
        LOG_DEBUG("network", "WORLD: HandleUpgradeItem - player lacks currency {} x{}.", itemUpgradeEntry->CurrencyID, itemUpgradeEntry->CurrencyCost);
        itemUpgradeResult.Success = false;
        SendPacket(itemUpgradeResult.Write());
        return;
    }

    uint32 currentUpgradeId = item->GetModifier(ITEM_MODIFIER_UPGRADE_ID);
    if (currentUpgradeId != itemUpgradeEntry->PrevItemUpgradeID)
    {
        LOG_DEBUG("network", "WORLD: HandleUpgradeItem - ItemUpgradeEntry ({}) does not follow the current upgrade ({}).", itemUpgradeEntry->ID, currentUpgradeId);
        itemUpgradeResult.Success = false;
        SendPacket(itemUpgradeResult.Write());
        return;
    }

    itemUpgradeResult.Success = true;
    SendPacket(itemUpgradeResult.Write());

    if (item->IsEquipped())
        _player->_ApplyItemBonuses(item, item->GetSlot(), false);

    item->SetModifier(ITEM_MODIFIER_UPGRADE_ID, itemUpgradeEntry->ID);

    if (item->IsEquipped())
        _player->_ApplyItemBonuses(item, item->GetSlot(), true);

    item->SetState(ITEM_CHANGED, _player);
    _player->ModifyCurrency(itemUpgradeEntry->CurrencyID, -int32(itemUpgradeEntry->CurrencyCost));
}
