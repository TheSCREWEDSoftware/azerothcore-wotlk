void WorldSession::SendListInventory(ObjectGuid vendorGuid, uint32 vendorEntry)
{
    LOG_DEBUG("network", "WORLD: Sent SMSG_VENDOR_INVENTORY");

    sScriptMgr->OnPlayerSendListInventory(GetPlayer(), vendorGuid, vendorEntry);

    Creature* vendor = GetPlayer()->GetNPCIfCanInteractWith(vendorGuid, UNIT_NPC_FLAG_VENDOR);
    if (!vendor)
    {
        LOG_DEBUG("network", "WORLD: SendListInventory - Unit ({}) not found or you can not interact with him.", vendorGuid.ToString());
        _player->SendSellError(SELL_ERR_CANT_FIND_VENDOR, nullptr, ObjectGuid::Empty, 0);
        return;
    }

    // remove fake death
    if (GetPlayer()->HasUnitState(UNIT_STATE_DIED))
    {
        GetPlayer()->RemoveAurasByType(SPELL_AURA_FEIGN_DEATH);
    }

    vendor->PauseMovementForInteraction();

    // Update home position for patrolling NPCs only (prevents drift for stationary NPCs)
    if (vendor->GetDefaultMovementType() == WAYPOINT_MOTION_TYPE ||
        vendor->GetMotionMaster()->GetCurrentMovementGeneratorType() == WAYPOINT_MOTION_TYPE)
        vendor->SetHomePosition(vendor->GetPosition());

    SetCurrentVendor(vendorEntry);

    VendorItemData const* items = vendorEntry ? sObjectMgr->GetNpcVendorItemList(vendorEntry) : vendor->GetVendorItems();
    if (!items)
    {
        WorldPackets::NPC::VendorInventory packet;
        packet.Vendor = vendorGuid;
        // 5.4.8 opens an empty list only when this is not 0, SkyFire sends it for armorers
        packet.Reason = vendor->IsArmorer() ? 1 : 0;
        SendPacket(packet.Write());
        return;
    }

    uint32 itemCount = items->GetItemCount();
    uint32 count = 0;

    WorldPackets::NPC::VendorInventory packet;
    packet.Vendor = vendorGuid;

    float discountMod = _player->GetReputationPriceDiscount(vendor);

    for (uint32 slot = 0; slot < itemCount; ++slot)
    {
        if (VendorItem const* item = items->GetItem(slot))
        {
            if (ItemTemplate const* itemTemplate = sObjectMgr->GetItemTemplate(item->item))
            {
                if (!(itemTemplate->AllowableClass & _player->getClassMask()) && itemTemplate->Bonding == BIND_WHEN_PICKED_UP && !_player->IsGameMaster())
                {
                    continue;
                }
                // Only display items in vendor lists for the team the
                // player is on. If GM on, display all items.
                if (!_player->IsGameMaster() && ((itemTemplate->HasFlag2(ITEM_FLAG2_FACTION_HORDE) && _player->GetTeamId() == TEAM_ALLIANCE) || (itemTemplate->HasFlag2(ITEM_FLAG2_FACTION_ALLIANCE) && _player->GetTeamId() == TEAM_HORDE)))
                {
                    continue;
                }

                // Items sold out are not displayed in list
                uint32 leftInStock = !item->maxcount ? 0xFFFFFFFF : vendor->GetVendorItemCurrentCount(item);
                if (!_player->IsGameMaster() && !leftInStock)
                {
                    continue;
                }

                ConditionList conditions = sConditionMgr->GetConditionsForNpcVendorEvent(vendor->GetEntry(), item->item);
                if (!sConditionMgr->IsObjectMeetToConditions(_player, vendor, conditions))
                {
                    LOG_DEBUG("network", "SendListInventory: conditions not met for creature entry {} item {}", vendor->GetEntry(), item->item);
                    continue;
                }

                // reputation discount
                int32 price = item->IsGoldRequired(itemTemplate) ? uint32(std::floor(itemTemplate->BuyPrice * discountMod)) : 0;

                WorldPackets::NPC::VendorItem vendorItem;
                vendorItem.MuID = slot + 1;     // client expects counting to start at 1
                vendorItem.Durability = itemTemplate->MaxDurability;
                if (item->ExtendedCost)
                    vendorItem.ExtendedCostID = item->ExtendedCost;
                // shortcut: npc_vendor has no type column in AC, so every row is a gold-priced item; add the
                // column together with the currency store when currency vendors are converted
                vendorItem.Type = ITEM_VENDOR_TYPE_ITEM;
                vendorItem.Quantity = static_cast<int32>(leftInStock);
                vendorItem.StackCount = itemTemplate->BuyCount;
                vendorItem.Price = price;
                vendorItem.Item.ItemID = item->item;
                packet.Items.push_back(vendorItem);

                if (++count >= MAX_VENDOR_ITEMS)
                {
                    break;
                }
            }
        }
    }

    // 5.4.8 opens an empty list only when this is not 0, SkyFire sends the vendor size or the armorer flag
    if (itemCount)
        packet.Reason = uint8(std::min<uint32>(itemCount, 255));
    else
        packet.Reason = vendor->IsArmorer() ? 1 : 0;

    SendPacket(packet.Write());
}

void WorldSession::HandleAutoStoreBagItemOpcode(WorldPackets::Item::AutoStoreBagItem& packet)
{
    //LOG_DEBUG("network.opcode", "WORLD: CMSG_AUTOSTORE_BAG_ITEM");
    Item* pItem = _player->GetItemByPos(packet.ContainerSlotA, packet.SlotA);
    if (!pItem)
        return;

    if (!_player->IsValidPos(packet.ContainerSlotB, NULL_SLOT, false))      // can be autostore pos
    {
        _player->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, nullptr, nullptr);
        return;
    }

    uint16 src = pItem->GetPos();

    // check unequip potability for equipped items and bank bags
    if (_player->IsEquipmentPos (src) || _player->IsBagPos (src))
    {
        InventoryResult msg = _player->CanUnequipItem(src, !_player->IsBagPos (src));
        if (msg != EQUIP_ERR_OK)
        {
            _player->SendEquipError(msg, pItem, nullptr);
            return;
        }
    }

    ItemPosCountVec dest;
    InventoryResult msg = _player->CanStoreItem(packet.ContainerSlotB, NULL_SLOT, dest, pItem, false);
    if (msg != EQUIP_ERR_OK)
    {
        _player->SendEquipError(msg, pItem, nullptr);
        return;
    }

    // no-op: placed in same slot
    if (dest.size() == 1 && dest[0].pos == src)
    {
        // just remove grey item state
        _player->SendEquipError(EQUIP_ERR_NONE, pItem, nullptr);
        return;
    }

    _player->RemoveItem(packet.ContainerSlotA, packet.SlotA, true);
    _player->StoreItem(dest, pItem, true);
    _player->UpdateTitansGrip();
}

